// Code128-B バーコード生成（外部ライブラリ非依存 / SSR・オフライン・CSP対応）
// Amazon FNSKU（英数字, 例 X00ABC1234）は Code128-B で表現できる。

// 各シンボルの「バー/スペース」幅パターン（インデックス 0..106）。
// 文字列の各桁が、バー・スペース・バー…の順のモジュール幅（1〜4）。
const PATTERNS = [
  "212222","222122","222221","121223","121322","131222","122213","122312",
  "132212","221213","221312","231212","112232","122132","122231","113222",
  "123122","123221","223211","221132","221231","213212","223112","312131",
  "311222","321122","321221","312212","322112","322211","212123","212321",
  "232121","111323","131123","131321","112313","132113","132311","211313",
  "231113","231311","112133","112331","132131","113123","113321","133121",
  "313121","211331","231131","213113","213311","213131","311123","311321",
  "331121","312113","312311","332111","314111","221411","431111","111224",
  "111422","121124","121421","141122","141221","112214","112412","122114",
  "122411","142112","142211","241211","221114","413111","241112","134111",
  "111242","121142","121241","114212","124112","124211","411212","421112",
  "421211","212141","214121","412121","111143","111341","131141","114113",
  "114311","411113","411311","113141","114131","311141","411131","211412",
  "211214","211232",
];
const STOP = "2331112"; // 停止パターン（13モジュール, 末尾バーあり）
const START_B = 104;

export interface BarSegment { x: number; width: number } // 黒バーのみ（x, width はモジュール単位）

export interface Code128Result {
  segments: BarSegment[]; // 描画すべき黒バー
  modules: number;        // 全体のモジュール数（quiet zone 除く）
  valid: boolean;
}

// Code128-B でエンコードして黒バー配列を返す。無効文字が含まれる場合 valid=false。
export function encodeCode128B(data: string): Code128Result {
  const values: number[] = [START_B];
  for (const ch of data) {
    const v = ch.charCodeAt(0) - 32; // Code B: ASCII 32..126 → 0..94
    if (v < 0 || v > 94) {
      return { segments: [], modules: 0, valid: false };
    }
    values.push(v);
  }
  // チェックサム（開始値 + Σ 値×位置）% 103
  let sum = START_B;
  for (let i = 1; i < values.length; i++) sum += values[i] * i;
  values.push(sum % 103);

  // パターン列を連結（各パターンはバー始まりで交互）
  const patternStr = values.map((v) => PATTERNS[v]).join("") + STOP;

  const segments: BarSegment[] = [];
  let x = 0;
  let isBar = true; // 先頭はバー
  for (const dch of patternStr) {
    const w = Number(dch);
    if (isBar) segments.push({ x, width: w });
    x += w;
    isBar = !isBar;
  }
  return { segments, modules: x, valid: true };
}
